"""Bounded, metadata-free raster media used by imports, service responses and recovery."""

import base64
import hashlib
import io
import warnings
from PIL import Image, UnidentifiedImageError

RASTER_VERSION = "raster-png-1"
MAX_IMAGE_BYTES = 12 * 1024 * 1024
MAX_PIXELS = 4096 * 4096


def _decode_png(data, transparent=False):
    if not data or len(data) > MAX_IMAGE_BYTES:
        raise ValueError("Raster asset exceeds byte budget")
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(io.BytesIO(data)) as source:
                if source.format != "PNG" or getattr(source, "n_frames", 1) != 1:
                    raise ValueError("Only single-frame PNG assets are accepted")
                w, h = source.size
                if min(w, h) < 64 or max(w, h) > 4096 or w * h > MAX_PIXELS:
                    raise ValueError("Raster geometry exceeds budget")
                image = source.convert("RGBA")
        alpha = image.getchannel("A").getextrema()
        if alpha[1] == 0 or (transparent and alpha[0] == 255):
            raise ValueError("Cutout needs actual transparency and visible pixels")
        return image, dict(width=w, height=h, has_alpha=alpha[0] < 255, format="png")
    except (
        OSError,
        UnidentifiedImageError,
        Image.DecompressionBombError,
        Image.DecompressionBombWarning,
    ) as exc:
        raise ValueError("Invalid raster image") from exc


def _encode_png(image):
    out = io.BytesIO()
    image.save(out, format="PNG", pnginfo=None)
    return out.getvalue()


def canonical_png(data, transparent=False):
    image, meta = _decode_png(data, transparent)
    blob = _encode_png(image)
    if len(blob) > MAX_IMAGE_BYTES:
        raise ValueError("Canonical raster exceeds byte budget")
    image.thumbnail((640, 640))
    return blob, _encode_png(image), meta


def png_thumbnail(data, size=320):
    image, _ = _decode_png(data)
    image.info.clear()
    image.thumbnail((size, size))
    return _encode_png(image)


def raster_receipt(req, data, key, identity, provider_request_id=None):
    blob, preview, meta = canonical_png(data, req.transparent)
    sha = hashlib.sha256(blob).hexdigest()
    return dict(
        request_hash=key,
        sha256=sha,
        filename=f"generated/{sha}.png",
        image_png=base64.b64encode(blob).decode(),
        request=req.model_dump(),
        factory_version=RASTER_VERSION,
        provider_identity=identity,
        provider_request_id=provider_request_id,
        provenance=(
            "configured image gateway output"
            if req.provider == "image_service"
            else "imported project image; not generated by this run"
        ),
        preview_filename=f"generated/{sha}.preview.png",
        preview_sha256=hashlib.sha256(preview).hexdigest(),
        preview_png=base64.b64encode(preview).decode(),
        **meta,
    )
